/*
 * TIM_BT.h - PS 侧驱动：PL 软 UART 上的蓝牙模块（HC-05 / HC-06 / JDY-31 等）
 *
 * ============================================================================
 * 【接线】注意 TX/RX 是交叉的
 *
 *   蓝牙模块 TX  ----  J12 PIN 7  (T5)  ----> FPGA bt_rx
 *   蓝牙模块 RX  <---  J12 PIN 5  (T9)  ----  FPGA bt_tx
 *   蓝牙模块 VCC ----  J12 PIN 1  (3V3)       ⚠️ 先确认模块是 3.3 V 电平
 *   蓝牙模块 GND ----  J12 PIN 2  (GND)       ⚠️ 必须共地
 *
 *   ★ "TX 接 TX" 是最常见的接错。判断方法：接反时发命令完全没反应，
 *     但 `BT_RX` 寄存器的 count 也不涨（因为字节根本没进来）。
 *     若 count 涨了但内容像乱码，那是波特率不对，不是接线。
 *
 * ============================================================================
 * 【为什么不复用 PS 的 UART0】
 *   本工程 PS 侧只有 UART1 引到 Type-C（0xF8401000），日志已经占了；
 *   UART0 没有引出到任何排针。要接第二个串口设备，只能在 PL 上做软 UART。
 *
 * ============================================================================
 * 【波特率】div = 50e6 / 115200 = 434.03 -> 写 434
 *   实际 115207 bps，误差 +0.006%，远小于 UART 的 2% 容限。
 *   与 V7 实测的日志口 115200 保持一致（用户已确认这个速率跑通过）。
 *
 *   ⚠️ 蓝牙模块本身的波特率默认常是 9600（HC-05/06 出厂值）。
 *      第一次用要先用 AT 命令把它改成 115200，或者把这里的 BT_DIV
 *      改成 50e6/9600 = 5208。改这里只影响 PL 侧，不用重新综合 ——
 *      Bt_SetBaud() 是运行时写寄存器。
 * ============================================================================
 */

#ifndef TIM_BT_H
#define TIM_BT_H

#include "ui_type.h"

/* ---------------- 寄存器偏移（相对 AXI_PWM_BASE = 0x80200000） ---------------- */
#define BT_REG_RX   0x60U   /* RO  [7:0]字节 [8]有新字节(读清) [16:9]计数低8位 */
#define BT_REG_TX   0x64U   /* WO  [7:0]要发的字节                              */
#define BT_REG_CFG  0x68U   /* RW  [15:0]分频 [16]使能 [17]发送忙(RO)           */

/* ---------------- 位定义 ---------------- */
#define BT_CFG_EN       (1U << 16)
#define BT_CFG_BUSY     (1U << 17)   /* 只读：正在发 */
#define BT_RX_FRESH     (1U << 8)    /* 只读：有新字节 */

/* ---------------- 常用分频值（f_clk = 50 MHz） ---------------- */
#define BT_DIV_9600     5208U
#define BT_DIV_19200    2604U
#define BT_DIV_38400    1302U
#define BT_DIV_57600    868U
#define BT_DIV_115200   434U

/* ---------------- API ---------------- */

/* 初始化：开 FIFO（其实是单字节缓冲）、设 115200、打印配置。
 * 上电会往蓝牙发一行 "FPGA ready\r\n" —— 手机端能收到就说明 TX 通路通。 */
void Bt_Init(void);

/* 取一个收到的字节。返回 1 = 取到（写进 *b），0 = 没有新字节。
 *
 * ★ 这个函数**顺便把 fresh 标志清掉**（RTL 里读 BT_RX 就清），
 *   所以调用方不需要再写一个"确认"寄存器。
 *
 * ★ 内部只读一次寄存器，不循环：一个 tick 里想取干净就 while 它。 */
u32  Bt_PollByte(u8 *b);

/* 发一个字节。**阻塞 1 ms**（无条件等待，不判忙位）。
 *
 * ★ 为什么不判 BT_CFG[17]：PS 写完 BT_TX 到 PL 把 tx_active 置 1 之间
 *   有一拍（20 ns）窗口，此刻读会得到 busy=0 而提前返回，下一字节
 *   就会覆盖掉正在发的那一个。连续发字符串时这个坑会表现为"偶尔缺字"。
 *   1 ms 对 115200 的 87 µs 是 11 倍余量，而且这个等待本来就在
 *   "等手机发下一字节"的空档里，不额外拖慢回环。
 *
 * ★ 蓝牙没接时也不会卡死（纯软件延时）。
 * ★ RTL 的 TX 只有单字节缓冲，所以**必须**逐字节调用，不能并发。 */
void Bt_SendByte(u8 b);

/* 发一个以 '\0' 结尾的字符串（逐字节走 Bt_SendByte） */
void Bt_SendStr(const char *s);

/* 改波特率。div 取 BT_DIV_* 之一 */
void Bt_SetBaud(u32 div);

/* 读 BT_CFG（[15:0] 分频，[16] 使能，[17] 发送忙） */
u32  Bt_ReadCfg(void);

/* 累计收到的字节数（低 8 位，会回绕）。用来判断"线路到底有没有字节"：
 * 发命令后这个数不动 = 接线错或模块没上电；动了但内容乱 = 波特率错。
 *
 * ⚠️⚠️ 读它会**清掉 BT_RX 的 fresh 标志**（RTL 里"读 0x60 就清"）。
 *       也就是说：此刻若正好有一个字节还没被 Bt_PollByte 取走，
 *       读一次这个函数就会把它静默吞掉。
 *
 *       ⇒ 只能用在"确认没有待读字节"的时刻（上电初始化、或停手几秒后
 *         做一次诊断）。**绝对不要放进主循环或心跳打印里**。
 *         这也是 BT_TEST / V8 两个分区的心跳都不打它的原因。 */
u32  Bt_ReadRxCount(void);

#endif /* TIM_BT_H */
