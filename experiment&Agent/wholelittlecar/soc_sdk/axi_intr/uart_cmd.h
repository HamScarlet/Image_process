/*
 * uart_cmd.h - V7 串口命令链：帧协议 + 命令表 + 执行
 *
 * ============================================================================
 * 【帧格式】（固定 10 字节，参考 refer 的 0x55×4 / 0x56×4 头尾）
 *
 *   0x55 0x55 0x55 0x55 | CMD | ARG | 0x56 0x56 0x56 0x56
 *   └── 4 字节帧头 ──┘  └ 2 字节载荷 ┘ └── 4 字节帧尾 ──┘
 *
 *   为什么头部要 4 个 0x55：
 *     单字节帧头太容易撞上。上电瞬间线上有杂波、插拔插头有抖动，
 *     这些都会被当成帧头，车就会"没人命令却动起来"。
 *     4 个连续 0x55 的概率极低，且丢失几个字节后仍能自愈。
 *
 *   为什么载荷是固定 2 字节、不带长度字段：
 *     长度字段本身也要靠帧头对齐才可信；固定长度 + 计数式状态机，
 *     载荷里出现 0x55 / 0x56 也不会破帧（见 V7_ParserSelfTest 第 4 例）。
 *
 * ============================================================================
 * 【命令表】ARG 一律是 0..100 的百分比，超出被限到 V7_MAX_DUTY_PCT
 *
 *   0x00 STOP    停止：占空比归零 + 刹停（ARG 忽略）
 *   0x01 FWD     前进：两轮同速同向
 *   0x02 BACK    后退：两轮同速反向
 *   0x03 SPIN_L  原地左转：左退右进
 *   0x04 SPIN_R  原地右转：左进右退
 *   0x05 ARC_L   差速左弯：左 = ARG/2（慢）、右 = ARG（快）⇒ 车头向左
 *   0x06 ARC_R   差速右弯：左 = ARG（快）、右 = ARG/2（慢）⇒ 车头向右
 *   0x7F PING    心跳：只回一行 ACK，不动电机
 *
 *   差速方向依据 V5 实测：外侧轮走的路更长 ⇒ 外侧轮必须更快。
 *   "左边给得多就往左转"是错的，别照直觉改。
 *
 * ============================================================================
 * 【三条设计约束】
 *
 *   1) 非阻塞：V7_Task() 每轮只做"捞干净 RX FIFO + 至多执行一次命令"，
 *      不等待、不睡眠（唯一例外是方向反转时故意插 V7_REVERSE_BRAKE_MS，
 *      见 uart_cmd.c 里的说明）。
 *
 *   2) 命令合并：一次 tick 里收到多帧时，只执行最后一帧。
 *      这样"连发两条"天然表现为"只执行最后一条"，不需要额外的去抖逻辑。
 *
 *   3) 看门狗：超过 V7_WDG_MS 没收到有效帧且车还在动，自动 STOP。
 *      遥控车丢包不能让它一直冲出去 —— 这是 V7 之后所有分区的安全底线。
 * ============================================================================
 */

#ifndef UART_CMD_H
#define UART_CMD_H

#include "ui_type.h"

/* ---------------- 帧结构 ---------------- */
#define V7_HEAD             0x55U
#define V7_TAIL             0x56U
#define V7_HEAD_LEN         4U
#define V7_TAIL_LEN         4U
#define V7_FRAME_LEN        10U     /* 4 + CMD + ARG + 4 */

/* ---------------- 命令表 ---------------- */
#define V7_CMD_STOP         0x00U
#define V7_CMD_FWD          0x01U
#define V7_CMD_BACK         0x02U
#define V7_CMD_SPIN_L       0x03U
#define V7_CMD_SPIN_R       0x04U
#define V7_CMD_ARC_L        0x05U
#define V7_CMD_ARC_R        0x06U
#define V7_CMD_PING         0x7FU

/* ---------------- 2026-11-02 V8 新增：速度档位 ----------------
 *
 *   这三个是给"蓝牙单字节"用的，但 10 字节帧里也能用（同一张表）。
 *
 *   ★★ 值域红线：所有命令码必须 < 0x0A ★★
 *      ASCII 文本里最小的可打印控制字符是 '\n' = 0x0A，其余都 ≥ 0x0D。
 *      只要命令全在 0x00–0x09，那么"人打的任何字"都不可能撞上命令 ——
 *      手机 App 的连接提示 "+CONN"、"OK"、模块回的 "AT+BAUD8" 全都安全。
 *      这条红线换来的是"解析器零状态、天然抗误触发"，比校验和还管用。
 *
 *      以后要加新命令，请跳到 0x10–0x1F 这一段：
 *      那里同样碰不到 ASCII 可打印字符（0x20 起才是空格）。
 *      **不要用 0x0A–0x0F**，'\\n' 和 '\\r' 就在里面。
 */
#define V7_CMD_SPD_UP       0x07U   /* 升一档（+5%），档位表见 main.c 的 V8_SPD_* */
#define V7_CMD_SPD_DN       0x08U   /* 降一档（-5%）                            */
#define V7_CMD_SPD_RST      0x09U   /* 回到默认档（3 档 = 30%）                 */

/* 0x0A / 0x0D 是 '\n' / '\r'，永远不能当命令用。
 * 0x0B / 0x0C 是 VT / FF，属于不可打印控制字符 —— 手打不出来，所以安全。 */
#define V7_CMD_TRIM_UP      0x0BU   /* 直线微调 +1%（右轮加速，车头往左修） */
#define V7_CMD_TRIM_DN      0x0CU   /* 直线微调 -1%（左轮加速）             */

/* 0x10 起是"第二段"值域（0x0A–0x0F 留给 '\n' / '\r'，不能用）。
 * 0x10 碰不到 ASCII 可打印字符（0x20 起才是空格），所以同样安全。 */
#define V7_CMD_GRD_CLR      0x10U   /* 清门控锁存：超声卡住时救命 */

/* 0x11–0x1F = 直达档位：码值减去 0x10 就是档号（1..15）。
 * 只有 15 个码，所以 16/17 档（100%）仍需用 0x07 升上去。
 * 这一段的用例：手机端做 15 个数字按钮，一键直达，不用连按十几下 0x07。 */
#define V8_CMD_GEAR_BASE    0x10U
#define V8_CMD_GEAR_MAX     0x1FU

/* ---------------- 安全限值 ----------------
 * V7_MAX_DUTY_PCT：上限放开到 100%（2026-11-02 用户要求更宽的速度范围，
 * 原来卡在 60% 是因为 V5 只验到 60%、双通道满载发热未测）。
 * ⚠️ 100% 时电机吃电池全压、TB6612 两通道同时满载，**只在架空时试**；
 *    落地跑建议 ≤70%，且 9 V 方块电池在高占空比下会掉压导致串口复位。
 * 超限命令会被削到这个值并打印一行提示，不是静默截断。 */
#define V7_MAX_DUTY_PCT     100U

/* 方向反转时插入的"断电 + 刹停"时长。20 ms 内到达的字节可能丢 1 帧，
 * 但状态机会从下一帧的 4 字节帧头自愈 —— 属设计取舍，不是 bug。 */
#define V7_REVERSE_BRAKE_MS 20U

/* 看门狗：这么久没有有效帧且车还在动，就自动停 */
#define V7_WDG_MS           500U

/* 半帧超时：帧收到一半停住了，超过这么久就丢弃重来 */
#define V7_FRAME_GAP_MS     50U

/* 心跳打印间隔。故意留着：它同时证明"主循环还活着"和"这 5 s 里有没有字节"。
 * 一行约 0.7 ms，RX FIFO 有 16 字节（1.4 ms）余量，不会把命令冲掉。 */
#define V7_HEARTBEAT_MS     5000U

/* ---------------- 统计（判断"错帧不误触发"用） ---------------- */
typedef struct {
    u32 bytes;      /* 收到的总字节数            */
    u32 good;       /* 收齐且校验通过的有效帧    */
    u32 noise;      /* 等帧头时遇到的非 0x55 字节 */
    u32 bad_tail;   /* 帧头对了但帧尾不对        */
    u32 gaps;       /* 半帧超时被丢弃            */
    u32 wdg;        /* 看门狗触发次数            */
} V7_Stats;

extern V7_Stats g_v7;

/* ---------------- 接口 ---------------- */

/* 初始化：开 RX FIFO、拉高 STBY、跑解析器自测、打印命令表。
 * 自测失败会打印 FAIL 并慢闪 —— 解析器不对时不要往下测。 */
void V7_Init(void);

/* 主循环里每次调用：捞字节 → 合并 → 执行 → 喂看门狗。非阻塞。 */
void V7_Task(void);

/* 打印统计（也可在主循环里定期调） */
void V7_PrintStats(void);

/* 解析器自测（不碰硬件，喂合成字节流）。返回 0 = 全过；n = 第 n 例失败 */
u32  V7_ParserSelfTest(void);

/* 单个字节喂进状态机。收齐一帧返回 1，并写出 cmd/arg */
u32  V7_FeedByte(u8 b, u8 *cmd, u8 *arg);

/* 直接执行一条命令（不经解析器）。
 *
 * ★ V8 起蓝牙的**单字节指令**也走这里 —— 这样"从日志口来的命令"和
 *   "从蓝牙来的命令"共用同一套执行逻辑（方向编码 / 60% 限幅 / 20 ms
 *   换向保护），不会出现"一个入口会刹、另一个不会"的割裂。
 *
 * ★ 注意它维护的是文件内静态状态（当前方向 / 当前占空比），所以
 *   **不要绕过它去直接写 Gpio1/PWM**，否则换向保护会漏判。
 *
 * ★ 遇到未知 cmd（含 0x07–0x09 这三个"档位"命令）只打印一行并忽略，
 *   不动电机。档位命令由调用方（V8 主循环）自己处理后，再用新的
 *   占空比重新调一次本函数。 */
void V7_Apply(u8 cmd, u8 arg);

#endif /* UART_CMD_H */
